// Bundle the JSON files written by `quoteline export` into one data.js, so the
// page works when opened straight from disk (browsers block fetch() on file://).
//
//   node build-data.mjs <export-dir> [out-file]
//
// The result is `window.QUOTELINE = { backtest, informed_sweep, ... }`.

import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { join, resolve } from "node:path";

const dir = process.argv[2];
const out = resolve(process.argv[3] ?? "data.js");
if (!dir) {
  console.error("usage: node build-data.mjs <export-dir> [out-file]");
  process.exit(2);
}

const names = [
  "backtest",
  "informed_sweep",
  "gamma_sweep",
  "surface",
  "hedging",
  "etf",
  "risk",
  "replay",
];

const bundle = {};
for (const n of names) {
  const p = join(dir, `${n}.json`);
  if (!existsSync(p)) {
    console.error(`missing ${p} - run: quoteline export --out ${dir}`);
    process.exit(1);
  }
  // Parsing here means a malformed file fails the build, not the page.
  bundle[n] = JSON.parse(readFileSync(p, "utf8"));
}

writeFileSync(
  out,
  "// Generated by build-data.mjs from `quoteline export`. Do not edit.\n" +
    `window.QUOTELINE = ${JSON.stringify(bundle)};\n`,
);
console.log(`wrote ${out} (${names.length} datasets)`);
